#!/usr/bin/env python3
"""Generates builtin/method/casemap.c: Unicode simple case mapping for to_upper()/to_lower().

A code point is mapped only when its upper (or lower) case is exactly one code point, so
`ß` stays `ß` (its full upper case is "SS") and `İ` is left alone. Runs of code points that
move by the same distance are stored as one range; Latin Extended-A style pairs
(Ā ā Ă ă ...) are ranges with stride 2.

    python3 tools/gen_casemap.py > builtin/method/casemap.c
"""
import sys
import unicodedata


def mappings(convert):
    out = []
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        mapped = convert(chr(cp))
        if len(mapped) == 1 and ord(mapped) != cp:
            out.append((cp, ord(mapped)))
    return out


def ranges(pairs):
    """Greedy runs of (first, last, delta, stride)."""
    result = []
    i = 0
    while i < len(pairs):
        first, target = pairs[i]
        delta = target - first
        stride = 1
        last = first
        if i + 1 < len(pairs) and pairs[i + 1][1] - pairs[i + 1][0] == delta:
            stride = pairs[i + 1][0] - first
            if stride not in (1, 2):
                stride = 1
        j = i + 1
        while (j < len(pairs) and pairs[j][0] == last + stride
               and pairs[j][1] - pairs[j][0] == delta):
            last = pairs[j][0]
            j += 1
        result.append((first, last, delta, stride))
        i = j
    return result


def emit(name, items):
    print(f"static const CaseRange {name}[] = {{")
    for first, last, delta, stride in items:
        print(f"    {{0x{first:X}, 0x{last:X}, {delta}, {stride}}},")
    print("};\n")


def main():
    upper = ranges(mappings(str.upper))
    lower = ranges(mappings(str.lower))
    print("/* Generated by tools/gen_casemap.py (Unicode %s). Do not edit. */" % unicodedata.unidata_version)
    print('#include "method/casemap.h"\n')
    print("typedef struct CaseRange {\n    uint32_t first;\n    uint32_t last;\n    int32_t delta;\n    uint32_t stride;\n} CaseRange;\n")
    emit("upper_ranges", upper)
    emit("lower_ranges", lower)
    print("""static uint32_t convert(const CaseRange *table, size_t count, uint32_t cp) {
    size_t low = 0;
    size_t high = count;
    while (low < high) {
        size_t middle = low + (high - low) / 2;
        const CaseRange *range = &table[middle];
        if (cp < range->first) {
            high = middle;
        } else if (cp > range->last) {
            low = middle + 1;
        } else {
            return (cp - range->first) % range->stride == 0 ? (uint32_t)((int32_t)cp + range->delta) : cp;
        }
    }
    return cp;
}

uint32_t lz_case_upper(uint32_t cp) {
    return convert(upper_ranges, sizeof upper_ranges / sizeof upper_ranges[0], cp);
}

uint32_t lz_case_lower(uint32_t cp) {
    return convert(lower_ranges, sizeof lower_ranges / sizeof lower_ranges[0], cp);
}""")
    sys.stderr.write("upper ranges: %d, lower ranges: %d\n" % (len(upper), len(lower)))


main()
