#!/bin/sh
# Writes mk/tests.am (automake syntax) from tests/tests.list, the single list of tests that
# both `make check` and tools/build-plain.sh use. autogen.sh runs it; the sources_sync test fails
# when mk/tests.am is stale.   usage: sh tools/gen-tests-am.sh [path/to/tests.list] > mk/tests.am
here=$(cd "$(dirname "$0")/.." && pwd)
list=${1:-$here/tests/tests.list}
awk '
BEGIN {
    print "# Generated by tools/gen-tests-am.sh from tests/tests.list. Do not edit."
    print "# (autogen.sh regenerates it; the sources_sync test fails when it is stale.)"
}
/^[ \t]*#/ || NF == 0 { next }
{
    name = $1; prog = $2; build = $3
    all[++n] = name
    if (build == "plain" || build == "ge" || build == "engine" || build == "utils") {
        progs[++np] = prog
        src = prog; sub(/_ge$/, "", src)
        body = body prog "_SOURCES = tests/" src ".c\n"
        if (build == "ge")
            body = body prog "_CFLAGS = $(AM_CFLAGS) -include $(top_srcdir)/tests/engine_redirect.h\n"
        if (build == "plain") body = body prog "_LDADD = $(LZ_LDADD_PLAIN)\n"
        else if (build == "utils") body = body prog "_LDADD = liblizard_utils.a\n"
        else body = body prog "_LDADD = $(LZ_LDADD_ENGINE)\n"
    } else {
        stubs[++ns] = name
    }
}
END {
    print "if LZ_RUN_TESTS"
    printf "check_PROGRAMS ="
    for (i = 1; i <= np; i++) printf " \\\n\t%s", progs[i]
    printf "\n\ncheck_SCRIPTS ="
    for (i = 1; i <= ns; i++) printf " \\\n\t%s", stubs[i]
    printf "\n\nTESTS ="
    for (i = 1; i <= n; i++) printf " \\\n\t%s", all[i]
    printf "\n\n%s\n", body
    print "# Tests that are not programs of their own (variants, scripts) are stubs: the file only has"
    print "# to exist; tests/run-test.sh looks the test up in tests/tests.list by its name."
    for (i = 1; i <= ns; i++) printf "%s:\n\t@$(lz_make_stub)\n", stubs[i]
    print "else"
    print "check_PROGRAMS ="
    print "check_SCRIPTS ="
    print "TESTS ="
    print "endif"
}' "$list"
